def load_live(arg):
    if arg:
        return json.load(open(arg))
    req = urllib.request.Request(LIVE_URL, headers={"User-Agent": "seoscoreapi-openapi-build"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def to_30(node):
    """Rewrite the OpenAPI 3.1 / JSON Schema 2020-12 constructs FastAPI emits into 3.0.3."""
    if isinstance(node, list):
        return [to_30(v) for v in node]
    if not isinstance(node, dict):
        return node
    node = {k: to_30(v) for k, v in node.items()}
    for key in ("anyOf", "oneOf"):
        alts = node.get(key)
        if isinstance(alts, list) and any(a == {"type": "null"} for a in alts):
            rest = [a for a in alts if a != {"type": "null"}]
            node.pop(key)
            if len(rest) == 1:
                node.update({k: v for k, v in rest[0].items() if k not in node})
            else:
                node[key] = rest
            node["nullable"] = True
    if isinstance(node.get("type"), list):
        types = [t for t in node["type"] if t != "null"]
        if len(types) < len(node["type"]):
            node["nullable"] = True
        node["type"] = types[0] if len(types) == 1 else node["type"]
    if "examples" in node and isinstance(node["examples"], list) and "type" in node:
        ex = node.pop("examples")
        if ex:
            node.setdefault("example", ex[0])
    if "const" in node:
        node["enum"] = [node.pop("const")]
    return node


def trim(o, n=2):
    """Keep the first n entries of every `checks` list so example responses stay readable."""
    if isinstance(o, dict):
        return {k: (trim(v[:n], n) if k == "checks" and isinstance(v, list) else trim(v, n)) for k, v in o.items()}
    if isinstance(o, list):
        return [trim(v, n) for v in o]
    return o


