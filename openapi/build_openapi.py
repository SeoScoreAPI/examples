def error_responses():
    def resp(desc, ex):
        return {"description": desc, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}, "example": ex}}}
    return {
        "400": resp("The URL was refused before any audit ran (malformed, or a private or internal address).", {"detail": "Invalid URL", "reason": "invalid_url"}),
        "401": resp("Missing or invalid API key.", {"detail": "Invalid or inactive API key. Get one at POST /signup"}),
        "422": resp("The page could not be loaded, so there is nothing to score. `reason` says why. Also returned when `url` is missing.", {"detail": "The site refused our crawler.", "reason": "blocked"}),
        "429": resp("Rate limit or plan quota reached. Wait for `Retry-After` when present, or upgrade the plan.", {"detail": "Rate limit exceeded"}),
    }


def build(live):
    out_paths = {}
    for path, methods in live["paths"].items():
        if path.startswith(SKIP_PREFIX):
            continue
        for method, op in methods.items():
            if (method, path) in SKIP:
                continue
            op = copy.deepcopy(op)
            op["parameters"] = [p for p in op.get("parameters", []) if p.get("name") != "X-API-Key"]
            if not op["parameters"]:
                op.pop("parameters")
            if (method, path) in OPS:
                op_id, tag, summary = OPS[(method, path)]
                op["tags"] = [tag]
            elif (method, path) in CITATION_IDS:
                op_id, summary = CITATION_IDS[(method, path)], op.get("summary")
                op["tags"] = ["AI Citations"]
            else:
                raise SystemExit(f"New operation in the live schema, add it to OPS or SKIP: {method.upper()} {path}")
            op["operationId"] = op_id
            op["summary"] = summary
            op["security"] = [] if (method, path) in PUBLIC else [{"ApiKeyAuth": []}]
            # FastAPI's generic 422 points at HTTPValidationError; keep it, it is accurate.
            out_paths.setdefault(path, {})[method] = op

    audit_ex = trim(json.load(open(HERE / "examples/audit-full-response.json")))
    air_ex = trim(json.load(open(HERE / "examples/ai-readability-full-response.json")))
    errs = error_responses()
    a = out_paths["/audit"]["get"]
    a["responses"] = {"200": {"description": "The audit. The example is a real audit of https://seoscoreapi.com with each `checks` list cut to two entries.",
                              "content": {"application/json": {"schema": {"$ref": "#/components/schemas/AuditResponse"}, "example": audit_ex}}}, **copy.deepcopy(errs)}
    r = out_paths["/ai-readability"]["get"]
    r["responses"] = {"200": {"description": "The AI readability result. The example is a real result for https://seoscoreapi.com with each `checks` list cut to two entries.",
                              "content": {"application/json": {"schema": {"$ref": "#/components/schemas/AiReadability"}, "example": air_ex}}}, **copy.deepcopy(errs)}
    # Realistic parameter and body examples, so importers (Postman, RapidAPI) do not fill
    # requests with placeholder text.
    for path, methods in out_paths.items():
        for method, op in methods.items():
            for prm in op.get("parameters", []):
                ex = PARAM_EXAMPLES.get((path, prm["name"]), PARAM_EXAMPLES.get(prm["name"]))
                if ex is not None:
                    prm["example"] = ex
            body_ex = BODY_EXAMPLES.get((method, path))
            if body_ex is not None:
                op["requestBody"]["content"]["application/json"]["example"] = body_ex

    components = to_30(copy.deepcopy(live.get("components", {})))
    components.setdefault("schemas", {}).update(rich_schemas())
    components["securitySchemes"] = {"ApiKeyAuth": {"type": "apiKey", "in": "header", "name": "X-API-Key",
                                                    "description": "Your SEO Score API key. Free at https://seoscoreapi.com/#signup."}}
    doc = {
        "openapi": "3.0.3",
        "info": {
            "title": "SEO Score API",
            "version": live.get("info", {}).get("version", "1.0.0"),
            "description": DESCRIPTION,
            "termsOfService": "https://seoscoreapi.com/terms",
            "contact": {"name": "SEO Score API", "url": "https://seoscoreapi.com", "email": "info@seoscoreapi.com"},
            "x-logo": {"url": "https://raw.githubusercontent.com/SeoScoreAPI/examples/master/assets/seoscore-icon-512.png", "backgroundColor": "#FFFFFF"},
        },
        "externalDocs": {"description": "Documentation", "url": "https://seoscoreapi.com/docs"},
        "servers": [{"url": "https://seoscoreapi.com"}],
        "security": [{"ApiKeyAuth": []}],
        "tags": TAGS,
        "paths": to_30(out_paths),
        "components": components,
    }
    return doc


def main():
    live = load_live(sys.argv[1] if len(sys.argv) > 1 else None)
    doc = build(live)
    (HERE / "seoscoreapi.openapi.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    (HERE / "seoscoreapi.openapi.yaml").write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120))
    n = sum(len(m) for m in doc["paths"].values())
    print(f"{n} operations, {len(doc['paths'])} paths")


if __name__ == "__main__":
    main()
